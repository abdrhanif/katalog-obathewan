function translateMedicalClean(text) {
  if (!text || typeof text !== 'string') return '';
  let s = text;
  for (const [regex, rep] of DICT) {
    s = s.replace(regex, rep);
  }
  return s.replace(/\s+/g, ' ').trim();
}

